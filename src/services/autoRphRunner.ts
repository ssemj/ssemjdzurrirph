// ============================================================
// Pelaksana RPH Automatik di pelayar
//  - mod AUTO_24J : jana semua kelas dari awal hari ini hingga +leadHours (lalai 24 jam)
//  - mod TRIGGER  : butang "Jana RPH Hari Ini" / tarikh dipilih
// RPH disimpan satu demi satu (Firebase + Google Sheet melalui callback `save`).
// ============================================================
import { doc, getDoc } from 'firebase/firestore';
import { db } from '../firebaseConfig';
import { AcademicCalendar, ERPHData } from '../types';
import { Occurrence, autoErphId, findExisting, mytToMs, occurrencesBetween, occurrencesOnDate, mytDateStr, mondayOfStr, nextMondayStr, needsNextMonday } from './autoRphCore';
import { AutoResult, GenerateCtx, generateForOccurrence } from './autoRphGenerate';
import { getGeminiKey } from './geminiService';

export interface RunOptions extends Omit<GenerateCtx, 'generatedBy'> {
  calendar: AcademicCalendar | null;
  mode: 'AUTO_24J' | 'TRIGGER' | 'WEEK';
  date?: string;                    // TRIGGER: tarikh; WEEK: mana-mana tarikh dalam minggu itu
  shouldStop?: () => boolean;       // butang Henti
  regenerateAutoDrafts?: boolean;   // TRIGGER: tulis semula RPH automatik yang masih DRAF
  save: (erph: ERPHData) => Promise<void>;
  onProgress?: (msg: string, done: number, total: number) => void;
  nowMs?: number;
}

export interface RunReport { results: AutoResult[]; created: number; skipped: number; errors: number; ranAt: string }

const LOCK_KEY = 'autorph_lock';
const takeLock = () => {
  try {
    const t = Number(localStorage.getItem(LOCK_KEY) || 0);
    if (Date.now() - t < 5 * 60 * 1000) return false;   // tab lain sedang menjana
    localStorage.setItem(LOCK_KEY, String(Date.now()));
  } catch { /* abaikan */ }
  return true;
};
const releaseLock = () => { try { localStorage.removeItem(LOCK_KEY); } catch { /* abaikan */ } };

const remoteExists = async (id: string) => {
  try {
    const snap = await Promise.race([getDoc(doc(db, 'erph_records', id)), new Promise<null>(r => setTimeout(() => r(null), 6000))]);
    if (!snap) return null;
    const d: any = snap.exists() ? snap.data() : null;
    return d ? (d as ERPHData) : null;   // termasuk DELETED (dipadam guru → jangan jana semula)
  } catch { return null; }
};

/** Senarai kelas yang akan diproses (untuk paparan "Akan datang"). */
export function plannedOccurrences(o: Pick<RunOptions, 'slots' | 'calendar' | 'settings' | 'mode' | 'date' | 'nowMs'>): Occurrence[] {
  const now = o.nowMs ?? Date.now();
  if (o.mode === 'TRIGGER') return occurrencesOnDate(o.slots, o.calendar, o.date || mytDateStr(now));
  if (o.mode === 'WEEK') {
    // Hantaran mingguan: Isnin minggu ini → Isnin minggu hadapan (termasuk)
    const mon = mondayOfStr(o.date || mytDateStr(now));
    return occurrencesBetween(o.slots, o.calendar, mytToMs(mon, '00:00'), mytToMs(nextMondayStr(mon), '23:59'));
  }
  const from = mytToMs(mytDateStr(now), '00:00');             // termasuk kelas awal hari ini yang belum ada RPH
  let to = now + (o.settings.leadHours || 24) * 3600 * 1000;
  // Khamis–Ahad: siapkan juga RPH Isnin minggu hadapan (untuk hantaran Isnin ke Isnin)
  if (needsNextMonday(now)) to = Math.max(to, mytToMs(nextMondayStr(mytDateStr(now)), '23:59'));
  return occurrencesBetween(o.slots, o.calendar, from, to);
}

export async function runAutoRph(o: RunOptions): Promise<RunReport> {
  const report: RunReport = { results: [], created: 0, skipped: 0, errors: 0, ranAt: new Date().toISOString() };
  if (!getGeminiKey()) throw new Error('Kunci API Gemini belum ditetapkan (menu Tetapan).');
  if (o.mode === 'AUTO_24J' && !takeLock()) return report;
  try {
    const occs = plannedOccurrences(o);
    const known = [...o.erphs];
    for (let i = 0; i < occs.length; i++) {
      if (o.shouldStop?.()) { o.onProgress?.('Dihentikan oleh guru', i, occs.length); break; }
      const occ = occs[i];
      const label = `${occ.day} ${occ.slot.startTime} • ${occ.slot.subject} ${occ.slot.classTitle || occ.slot.className}`;
      o.onProgress?.(`Menjana ${label}...`, i, occs.length);

      let existing = findExisting(known, o.teacherId, occ);
      const id = autoErphId(o.teacherId, occ.date, occ.slot.startTime, occ.slot.classTitle || '', occ.slot.subject);
      if (!existing) existing = (await remoteExists(id)) || undefined;
      const canOverwrite = o.mode !== 'AUTO_24J' && o.regenerateAutoDrafts && existing?.autoGenerated && existing.status === 'DRAFT';   // DELETED tidak ditulis semula
      if (existing && !canOverwrite) {
        const deleted = (existing as any).status === 'DELETED';
        report.results.push({ occ, status: deleted ? 'SKIPPED' : 'EXISTS', message: deleted ? 'Dipadam guru — tidak dijana' : existing.autoGenerated ? 'Sudah dijana' : 'Sudah ditulis guru', erph: deleted ? undefined : existing });
        continue;
      }
      try {
        const res = await generateForOccurrence(occ, { ...o, erphs: known, generatedBy: o.mode === 'AUTO_24J' ? 'AUTO_24J' : 'TRIGGER' });
        if (o.shouldStop?.()) break;   // hasil selepas Henti diabaikan
        if (res.status === 'CREATED' && res.erph) {
          await o.save(res.erph);
          known.push(res.erph);
          report.created++;
        } else report.skipped++;
        report.results.push(res);
      } catch (e: any) {
        report.errors++;
        report.results.push({ occ, status: 'ERROR', message: String(e?.message || e).slice(0, 200) });
        if (/kunci api|api key|API_KEY_INVALID|PERMISSION_DENIED/i.test(String(e?.message))) break;
      }
      await new Promise(r => setTimeout(r, 800));   // elak had kadar Gemini
    }
    o.onProgress?.('Selesai', occs.length, occs.length);
    try { localStorage.setItem(`autorph_last_${o.teacherId}`, JSON.stringify({ ranAt: report.ranAt, created: report.created, skipped: report.skipped, errors: report.errors })); } catch { /* abaikan */ }
    return report;
  } finally {
    if (o.mode === 'AUTO_24J') releaseLock();
  }
}
