import { ERPHData, ERPHStatus, AutoPilotSettings, DskpDocument, RptDocument, ScheduleSlot } from '../types';
import { generateErphContent, effectiveLanguage, isManagementSubject, MGMT_SP_FALLBACK } from './geminiService';
import {
  Occurrence, autoErphId, isFutureWeek, dskpContextRows, durationLabel, findDskpDoc, findRptDoc, lastSpFor, lessonPosition, planLesson, isNonTeaching,
} from './autoRphCore';

export type AutoResultStatus = 'CREATED' | 'EXISTS' | 'SKIPPED' | 'ERROR';
export interface AutoResult {
  occ: Occurrence;
  status: AutoResultStatus;
  message: string;
  erph?: ERPHData;
}

export interface GenerateCtx {
  teacherId: string;
  teacherName: string;
  slots: ScheduleSlot[];
  settings: AutoPilotSettings;
  rptDocs: RptDocument[];
  dskpDocs: DskpDocument[];
  erphs: ERPHData[];          // RPH sedia ada (untuk sandaran turutan DSKP)
  generatedBy: 'AUTO_24J' | 'TRIGGER' | 'CLOUD';
}

/** Pulangkan RPH lengkap (status DRAF) atau sebab ia dilangkau. */
export async function generateForOccurrence(occ: Occurrence, ctx: GenerateCtx): Promise<AutoResult> {
  const s = occ.slot;
  if (occ.holiday) return { occ, status: 'SKIPPED', message: `Cuti: ${occ.holiday}` };
  if (isNonTeaching(s.subject)) return { occ, status: 'SKIPPED', message: 'Slot bukan PdP' };
  const mgmt = isManagementSubject(s.subject);
  if (mgmt && ctx.settings.skipManagement) return { occ, status: 'SKIPPED', message: 'Slot Pengurusan dilangkau (tetapan)' };

  const rpt = findRptDoc(ctx.rptDocs, s.subject, s.className);
  const dskp = findDskpDoc(ctx.dskpDocs, s.subject, s.className);
  let plan = mgmt ? null : planLesson({
    rpt, dskp, week: occ.week,
    position: lessonPosition(ctx.slots, s),
    lastSp: lastSpFor(ctx.erphs, ctx.teacherId, s, occ.date),
  });
  if (mgmt) {
    const sk = 'PERKONGSIAN PINTAR';
    plan = { title: 'PENGURUSAN DALAM BIDANG', field: '', sk, sp: MGMT_SP_FALLBACK[sk], notes: '', source: 'Pengurusan' };
  }
  if (!plan || (!plan.sk && !plan.sp)) {
    const why = occ.week == null ? 'Kalendar akademik belum ditetapkan'
      : !rpt && !dskp ? `Tiada RPT/DSKP untuk ${s.subject} ${s.className}`
      : `RPT tiada isi untuk Minggu ${occ.week}`;
    return { occ, status: 'SKIPPED', message: why };
  }

  const language = effectiveLanguage(s.subject, ctx.settings.language);
  const ai = await generateErphContent({
    subject: s.subject, form: s.className, classTitle: s.classTitle,
    title: plan.title, field: plan.field, sk: plan.sk, sp: plan.sp,
    dskpRows: dskpContextRows(dskp, plan.sk, plan.sp),
    language, duration: durationLabel(s.startTime, s.endTime),
    extraNotes: plan.notes ? `Cadangan aktiviti/PBD dari RPT: ${plan.notes}` : undefined,
  });

  const erph: ERPHData = {
    id: autoErphId(ctx.teacherId, occ.date, s.startTime, s.classTitle || '', s.subject),
    teacherId: ctx.teacherId, teacherName: ctx.teacherName,
    week: occ.week || 0, date: occ.date, day: occ.day,
    startTime: s.startTime, endTime: s.endTime,
    className: s.className, classTitle: s.classTitle, subject: s.subject,
    field: plan.field, title: plan.title, sk: plan.sk, sp: plan.sp, core: 'Teras',
    objective: ai.objective, activities: ai.activities, bbm: ai.bbm,
    reflection: isFutureWeek(occ.date) ? '' : ai.reflection,   // minggu hadapan: refleksi diisi selepas PdP
    language, status: ERPHStatus.DRAFT,
    autoGenerated: true, generatedAt: new Date().toISOString(), generatedBy: ctx.generatedBy,
    generatedFrom: [plan.source, dskp ? 'DSKP' : ''].filter(Boolean).join(' • '),
  };
  return { occ, status: 'CREATED', message: `Dijana (${erph.generatedFrom})`, erph };
}
